"""Orchestrates one governance analysis run for a submission (Stage 2: Automated Analysis)."""
import json
import re
from pathlib import Path

from backend import db
from backend.common import audit, now
from backend.services import image_checker, llm, pdf, text_checker


def load_rules():
    return db.query("SELECT * FROM rules ORDER BY id")


def get_settings():
    s = {r["key"]: r["value"] for r in db.query("SELECT * FROM settings")}
    return {"palette": json.loads(s.get("palette", "[]")), "min_contrast": float(s.get("min_contrast", 4.5)),
            "min_width": int(s.get("min_width", 800))}


def run_analysis(sub_id, user, reason="analysis"):
    sub = db.query("SELECT * FROM submissions WHERE id=?", (sub_id,), one=True)
    ver, st = sub["current_version"], get_settings()
    found, extra = [], {}
    text = sub["content_text"] or ""
    if text.strip():
        r = text_checker.analyze_text(text, load_rules())
        found += r["issues"]
        extra["verified_claims"], extra["text_metrics"] = r["verified_claims"], r["metrics"]
    if sub["image_path"]:
        r = image_checker.analyze_image(sub["image_path"], sub["alt_text"], text, st["palette"], st["min_contrast"], st["min_width"])
        found += r["issues"]
        extra["image_metrics"] = r["metrics"]

    prior = {(i["rule_key"], i["match"]) for i in db.query(
        "SELECT rule_key,match FROM issues WHERE submission_id=? AND status='dismissed'", (sub_id,))}
    db.execute("DELETE FROM issues WHERE submission_id=? AND version=?", (sub_id, ver))
    for i in found:
        status = "dismissed" if (i["rule_key"], i["match"]) in prior else "open"
        i["status"] = status
        db.execute(
            "INSERT INTO issues(submission_id,version,category,rule_key,severity,message,start,end,match,excerpt,suggestion,auto_fix,citation,bbox,status)"
            " VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (sub_id, ver, i["category"], i["rule_key"], i["severity"], i["message"], i["start"], i["end"], i["match"], i["excerpt"],
             i["suggestion"], int(i["auto_fix"]), json.dumps(i["citation"]), json.dumps(i["bbox"]) if i["bbox"] else None, status))
    sc = text_checker.score(found)
    legal = int(any(i["category"] in ("claims", "legal") and i["status"] != "fixed" for i in found))
    new_status = "analyzed" if sub["status"] == "draft" else sub["status"]
    db.execute("UPDATE submissions SET score=?, requires_legal=?, status=?, updated_at=? WHERE id=?", (sc, legal, new_status, now(), sub_id))
    audit(user, f"analysis.{reason}", "submission", sub_id, f"v{ver}: {len(found)} issue(s), score {sc}")
    return extra


def build_rewrite(sub_id):
    """Full-document intent-preserving rewrite: LLM if configured, otherwise apply all deterministic auto-fixes."""
    sub = db.query("SELECT * FROM submissions WHERE id=?", (sub_id,), one=True)
    issues = db.query("SELECT * FROM issues WHERE submission_id=? AND version=? AND status='open' AND start IS NOT NULL ORDER BY start",
                      (sub_id, sub["current_version"]))
    text = sub["content_text"] or ""
    dismissed = {(i["rule_key"], i["match"]) for i in db.query(
        "SELECT rule_key,match FROM issues WHERE submission_id=? AND status='dismissed'", (sub_id,))}
    rules, det = load_rules(), text
    for _ in range(3):  # fine-grained fixes first; coarse sentence-level claim rewrites in a later round
        found = [i for i in text_checker.analyze_text(det, rules)["issues"]
                 if i["suggestion"] is not None and i["start"] is not None and (i["rule_key"], i["match"]) not in dismissed]
        picked, taken = [], []
        for i in sorted(found, key=lambda i: (i["end"] - i["start"], i["start"])):
            if i["end"] == i["start"] or not any(i["start"] < b and i["end"] > a for a, b in taken):
                picked.append(i); taken.append((i["start"], i["end"]))
        if not picked:
            break
        out, cursor = [], 0
        for i in sorted(picked, key=lambda i: (i["start"], i["end"])):
            out.append(det[cursor:i["start"]]); out.append(i["suggestion"]); cursor = i["end"]
        out.append(det[cursor:])
        new = "".join(out)
        if new == det:
            break
        det = new
    mode = "rules"
    if llm.enabled() and issues:
        evidence = []
        for i in issues:
            c = json.loads(i["citation"] or "{}")
            if c.get("quote"):
                evidence.append(c["quote"][:200])
        masked = text_checker.mask_pii(text)
        res = llm.rewrite(masked, [i["message"] for i in issues], evidence[:6])
        if res:
            det, mode = res, "llm"
    return {"original": text, "rewrite": det, "mode": mode, "ai_disclosure": "Suggestion generated by AI; review before use." if mode == "llm" else
            "Suggestion generated by deterministic brand rules (no external AI used)."}


def extract_file_text(path, filename, with_pages=False):
    ext = Path(filename).suffix.lower()
    if ext == ".pdf":
        text, page_map = pdf.extract_text(path)
        return (text, page_map) if with_pages else text
    if ext in (".txt", ".md", ".markdown", ".csv"):
        t = Path(path).read_text(encoding="utf-8", errors="ignore")
        return (t, []) if with_pages else t
    raise ValueError("Unsupported file type. Use .md, .txt, .pdf, .png, .jpg or .jpeg")


def rescore(sub_id):
    """Recompute score/requires_legal from the current issue statuses (after dismiss/reopen)."""
    sub = db.query("SELECT current_version FROM submissions WHERE id=?", (sub_id,), one=True)
    cur = db.query("SELECT rule_key,severity,status,category FROM issues WHERE submission_id=? AND version=?", (sub_id, sub["current_version"]))
    legal = int(any(i["category"] in ("claims", "legal") and i["status"] != "fixed" for i in cur))
    db.execute("UPDATE submissions SET score=?, requires_legal=?, updated_at=? WHERE id=?", (text_checker.score(cur), legal, now(), sub_id))


def extras(sub_id):
    """Read-only extras for the detail view: verified claims (with evidence) and engine metrics."""
    sub = db.query("SELECT * FROM submissions WHERE id=?", (sub_id,), one=True)
    out = {}
    if (sub["content_text"] or "").strip():
        r = text_checker.analyze_text(sub["content_text"], load_rules())
        out["verified_claims"], out["text_metrics"] = r["verified_claims"], r["metrics"]
    if sub["image_path"]:
        st = get_settings()
        out["image_metrics"] = image_checker.analyze_image(sub["image_path"], sub["alt_text"], sub["content_text"], st["palette"], st["min_contrast"], st["min_width"])["metrics"]
    return out
